// verdiff compares two runs of the same rows, made with two iproute2
// versions on one kernel (goip-parity-next.md, NC3-T01), row by row: the
// exit status, the sequence of message types, each request's bytes (its
// type, flags and body; seq and pid differ run to run and aren't
// compared), and every .out file, ip's own and each readback's, with the
// random link-layer addresses blanked. A row is
// a directory holding cmd.json, named by its path under the run's root.

// verRow is what verdiff compares of one row.
type verRow struct {
	rc   string
	msgs []nlparity.Msg
	outs map[string][]byte
}

// verDiff is one difference: the row, what differs, and how.
type verDiff struct {
	Row, Kind, Detail string
}

func runVerdiff(args []string, stdout, stderr io.Writer) int {
	fs := flag.NewFlagSet("verdiff", flag.ContinueOnError)
	fs.SetOutput(stderr)
	a := fs.String("a", "", "the first run's root (rows under it, each a directory with cmd.json)")
	b := fs.String("b", "", "the second run's root")
	out := fs.String("out", "", "report file to write")
	if err := fs.Parse(args); err != nil {
		return 2
	}
	if *a == "" || *b == "" || *out == "" {
		fmt.Fprintln(stderr, "nlcapgen verdiff: -a, -b and -out are required")
		return 2
	}
	ra, err := loadVerRows(os.DirFS(*a))
	if err != nil {
		fmt.Fprintln(stderr, "nlcapgen verdiff:", err)
		return 1
	}
	rb, err := loadVerRows(os.DirFS(*b))
	if err != nil {
		fmt.Fprintln(stderr, "nlcapgen verdiff:", err)
		return 1
	}
	diffs := diffVerRows(ra, rb)
	header := []string{
		fmt.Sprintf("Generated by `nlcapgen verdiff -a %s -b %s`.", *a, *b),
		"Do not edit; regenerate. tools/nlcapgen/verdiff.go explains the comparison.",
	}
	if err := writeFile(*out, func(w io.Writer) error { return writeVerdiff(w, header, ra, rb, diffs) }); err != nil {
		fmt.Fprintln(stderr, "nlcapgen verdiff:", err)
		return 1
	}
	fmt.Fprintf(stdout, "%d rows, %d differences\n", len(ra), len(diffs))
	return 0
}

// loadVerRows reads every row under root.
func loadVerRows(root fs.FS) (map[string]verRow, error) {
	rows := map[string]verRow{}
	err := fs.WalkDir(root, ".", func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() || path.Base(p) != "cmd.json" {
			return err
		}
		dir := path.Dir(p)
		r, err := loadVerRow(root, dir)
		if err != nil {
			return fmt.Errorf("%s: %w", dir, err)
		}
		rows[dir] = r
		return nil
	})
	return rows, err
}

func loadVerRow(root fs.FS, dir string) (verRow, error) {
	r := verRow{outs: map[string][]byte{}}
	ents, err := fs.ReadDir(root, dir)
	if err != nil {
		return r, err
	}
	for _, e := range ents {
		name := e.Name()
		b, err := fs.ReadFile(root, path.Join(dir, name))
		switch {
		case e.IsDir():
			continue
		case err != nil:
			return r, err
		case name == "ip.rc":
			r.rc = strings.TrimSpace(string(b))
		case name == "ip.pcap":
			if r.msgs, err = verMsgs(b); err != nil {
				return r, err
			}
		case strings.HasSuffix(name, ".out"):
			r.outs[name] = verNormalize(b)
		}
	}
	return r, nil
}

// verLLAddr is a link-layer address of six octets or more: the kernel
// gives a dummy, a bridge or a VRF a random one at each creation. A bridge
// id prints its octets unpadded (8000.a:eb:1:4d:b3:9b).
var verLLAddr = regexp.MustCompile(`\b[0-9a-f]{1,2}(?::[0-9a-f]{1,2}){5,}\b`)

// verNormalize blanks what differs run to run in an output for reasons
// not ip's: the random link-layer addresses.
func verNormalize(b []byte) []byte {
	return verLLAddr.ReplaceAll(b, []byte("<lladdr>"))
}

// verMsgs is every netlink message in a capture, of any protocol, in
// capture order.
func verMsgs(b []byte) ([]nlparity.Msg, error) {
	_, recs, err := xtcpnl.ParseNetlinkPcap(b)
	if err != nil {
		return nil, err
	}
	var msgs []nlparity.Msg
	for _, rec := range recs {
		fam, body, err := rec.NetlinkPayload()
		if err != nil {
			return nil, err
		}
		d, err := nlparity.WalkDatagram(fam, body)
		if err != nil {
			return nil, err
		}
		for _, m := range d.Msgs {
			m.Proto = fam
			msgs = append(msgs, m)
		}
	}
	return msgs, nil
}

// diffVerRows lists every difference, by row, then kind.
func diffVerRows(a, b map[string]verRow) []verDiff {
	var out []verDiff
	for _, id := range verIDs(a, b) {
		ra, inA := a[id]
		rb, inB := b[id]
		switch {
		case !inB:
			out = append(out, verDiff{id, "missing", "only in -a"})
			continue
		case !inA:
			out = append(out, verDiff{id, "missing", "only in -b"})
			continue
		}
		if ra.rc != rb.rc {
			out = append(out, verDiff{id, "rc", ra.rc + " -> " + rb.rc})
		}
		ta, tb := verTypes(ra.msgs), verTypes(rb.msgs)
		if ta != tb {
			out = append(out, verDiff{id, "types", ta + " -> " + tb})
		} else {
			out = append(out, verRequests(id, ra.msgs, rb.msgs)...)
		}
		names := slices.Sorted(func(yield func(string) bool) {
			for k := range ra.outs {
				if !yield(k) {
					return
				}
			}
			for k := range rb.outs {
				if _, dup := ra.outs[k]; !dup && !yield(k) {
					return
				}
			}
		})
		for _, n := range names {
			oa, okA := ra.outs[n]
			ob, okB := rb.outs[n]
			if okA != okB || !bytes.Equal(oa, ob) {
				out = append(out, verDiff{id, "out", n})
			}
		}
	}
	return out
}

func verIDs(a, b map[string]verRow) []string {
	ids := make([]string, 0, len(a))
	for id := range a {
		ids = append(ids, id)
	}
	for id := range b {
		if _, ok := a[id]; !ok {
			ids = append(ids, id)
		}
	}
	slices.Sort(ids)
	return ids
}

// verTypes is a capture's message types, each with its protocol and R for
// a request: "0:18R 0:16 0:2".
func verTypes(msgs []nlparity.Msg) string {
	s := make([]string, len(msgs))
	for i, m := range msgs {
		s[i] = strconv.Itoa(int(m.Proto)) + ":" + strconv.Itoa(int(m.Hdr.Type))
		if m.Hdr.Flags&unix.NLM_F_REQUEST != 0 {
			s[i] += "R"
		}
	}
	return strings.Join(s, " ")
}

// verRequests compares the requests of two captures with the same types:
// for each that differs, its index among the requests, its type and the
// first differing byte, counted from its nlmsghdr.
func verRequests(id string, a, b []nlparity.Msg) []verDiff {
	var out []verDiff
	n := 0
	for i := range a {
		if a[i].Hdr.Flags&unix.NLM_F_REQUEST == 0 {
			continue
		}
		n++
		if off := verFirstDiff(a[i], b[i]); off >= 0 {
			out = append(out, verDiff{id, "request", fmt.Sprintf("%d (type %d) at byte %d", n, a[i].Hdr.Type, off)})
		}
	}
	return out
}

// verFirstDiff is the offset of the first byte two messages differ in,
// outside nlmsg_seq and nlmsg_pid, or -1.
func verFirstDiff(a, b nlparity.Msg) int {
	const flagsOff, bodyOff = 6, xtcpnl.NlMsgHdrSizeCst
	switch {
	case a.Hdr.Len != b.Hdr.Len:
		return 0
	case a.Hdr.Type != b.Hdr.Type:
		return 4
	case a.Hdr.Flags != b.Hdr.Flags:
		return flagsOff
	}
	// The same nlmsg_len, so the same body length.
	for i := range a.Body {
		if a.Body[i] != b.Body[i] {
			return bodyOff + i
		}
	}
	return -1
}

// writeVerdiff writes the report: the counts, then one line per
// difference.
func writeVerdiff(w io.Writer, header []string, a, b map[string]verRow, diffs []verDiff) error {
	var buf bytes.Buffer
	for _, h := range header {
		buf.WriteString("# " + h + "\n")
	}
	kinds := map[string]int{}
	rows := map[string]bool{}
	for _, d := range diffs {
		kinds[d.Kind]++
		rows[d.Row] = true
	}
	fmt.Fprintf(&buf, "# %d rows in -a, %d in -b; %d differ.\n", len(a), len(b), len(rows))
	for _, k := range []string{"missing", "rc", "types", "request", "out"} {
		fmt.Fprintf(&buf, "# %s: %d\n", k, kinds[k])
	}
	for _, d := range diffs {
		fmt.Fprintf(&buf, "%s\t%s\t%s\n", d.Row, d.Kind, d.Detail)
	}
	_, err := w.Write(buf.Bytes())
	return err
}
