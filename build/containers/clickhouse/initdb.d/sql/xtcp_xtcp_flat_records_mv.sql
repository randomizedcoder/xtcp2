  AS SELECT
    fromUnixTimestamp64Nano(timestamp_ns) AS timestamp_ns,
    * EXCEPT (timestamp_ns)
  FROM xtcp.xtcp_flat_records_kafka
  WHERE length(_error) == 0 AND schema_version = 2;

